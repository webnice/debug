/*

Package debug — отладочный дампер произвольных переменных.

Библиотека выводит значения любых типов в удобочитаемом виде: структуры — с
именами полей, карты — с ключами, срезы и массивы — с индексами. Каждая
строка дампа нумеруется, вложенность отражается отступами. Дамп
сопровождается заголовком с датой, местом вызова, именем пакета и функции,
и завершается строкой-разделителем:

	[ 11.11.2026 10:00:00:0000000000 ] ------------------------------------------------------------
	[                 debug.Dumper() ] /home/user/project/main.go:16 [main] [main()]
	000000: main.Config {
	000001: 	Host: "localhost"
	000002: 	Port: 8080
	000003: }
	-----------------------------------------------------------------------------------------------

Способы вывода:

	Dumper        — вывод дампа в STDOUT;
	DumperString  — дамп в виде строки, удобно передать в лог или тест;
	DumperByte    — дамп в виде []byte, удобно записать самостоятельно;
	DumperFile    — дамп в файл <имя программы>.txt в текущей директории,
	                данные дописываются в конец существующего файла;
	FileSave      — сохранение произвольных данных в файл с созданием
	                отсутствующих директорий и выбором имени и пути.

Библиотека бережно обращается с любыми данными:

  - циклические ссылки не приводят к зависанию: повторное вхождение объекта
    выводится как ссылка (obj @ N) на строку первого вывода;
  - пустые ссылочные поля структур (nil) скрываются фильтром;
  - значения, реализующие интерфейс error, выводятся текстом ошибки;
  - значения с методом String() выводятся результатом этого метода;
  - ключи карт сортируются, дамп воспроизводим между запусками;
  - срезы байт выводятся шестнадцатеричным литералом.

Поиск забытых отладочных вызовов. Функция Nop() ничего не делает, но
оставляет в коде точку, которую легко найти. При запуске программы с
переменной окружения DEBUG_CALLS каждый вызов Nop() выводит имя файла и
номер строки вызова:

	[                    debug.Nop() ] /home/user/project/main.go:22

Дамп со стеком вызовов. Функция SeeCallStack() включает или выключает вывод
полного стека всех горутин, который добавляется к каждому следующему дампу.
То же действие выполняет переменная окружения DEBUG_TRACESTACK.

Переменные окружения:

	DEBUG_CALLS      — вывод места вызова каждого Nop();
	DEBUG_TRACESTACK — добавление стека вызовов всех горутин к дампу;
	DEBUG_CRLF       — принудительное переключение окончаний строк CRLF/LF.

Распознаваемые значения: 1, t, true, y, yes, on — включить; 0, f, false,
n, no, off — выключить. Незаданная или нераспознанная переменная оставляет
поведение по умолчанию: окончания CRLF в Windows и LF в остальных системах,
остальные режимы выключены.

Пример использования:

	type Config struct {
		Host string
		Port int
		TLS  any // пустое ссылочное поле будет скрыто фильтром
	}

	func main() {
		cfg := Config{Host: "localhost", Port: 8080}
		debug.Dumper(cfg)
		s := debug.DumperString(cfg) // дамп в строку
		debug.DumperFile(cfg)        // дамп в файл <имя программы>.txt
	}

*/

package debug
